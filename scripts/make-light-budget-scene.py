#!/usr/bin/env python3
# Writes the light-budget scene: orbit.yaml with a few hundred more point lights over Ostra
# Highport's hull, the station-full of lights the cluster grid is sized for (docs/architecture.md,
# "The grid and the infinite far plane"). Phase 5e measured the grid, the cluster range and the
# light index list's budget against it. The scene names its star system and materials by virtual
# path, found through the asset mounts, so it can be written anywhere; it goes beside the orbit scene
# it is made from, in a build tree's asset copy rather than the source tree:
#
#   python3 scripts/make-light-budget-scene.py build/clang-release/assets/scene/orbit.yaml
#   build/clang-release/source/test/render_test \
#       --scene build/clang-release/assets/scene/light-budget.yaml --benchmark 600
#
# The seed is fixed: the same script makes the same scene.
import math, os, random, sys

if len(sys.argv) != 2:
    sys.exit('usage: make-light-budget-scene.py <path to orbit.yaml>')
source = sys.argv[1]
random.seed(11)
lights = []

def light(position):
    lights.append((position, random.uniform(6.0, 15.0), random.uniform(20.0, 60.0),
                   [round(random.uniform(0.6, 1.0), 2) for _ in range(3)]))

# Rings of lights along the hub, a metre off its surface; the station's axis is z.
for ring in range(15):
    z = -28.0 + 4.0 * ring
    for step in range(8):
        angle = 2.0 * math.pi * (step + 0.5 * (ring % 2)) / 8.0
        light((7.0 * math.cos(angle), 7.0 * math.sin(angle), z))
# Both faces of the collar's rim.
for face in (11.0, 13.0):
    for step in range(32):
        angle = 2.0 * math.pi * step / 32.0
        light((17.0 * math.cos(angle), 17.0 * math.sin(angle), face))
# Above and below the truss, over the containers.
for step in range(23):
    for height in (-4.0, 4.0):
        light((-44.0 + 4.0 * step, height, 0.0))
# Along the edges of the solar panels.
for side in (-56.0, 56.0):
    for step in range(6):
        for edge in (-8.0, 8.0):
            light((side - 10.0 + 4.0 * step, 1.0, edge))

with open(source) as file:
    text = file.read()
marker = '  - id: camera\n'
if marker not in text:
    sys.exit('make-light-budget-scene: no camera entity to put the lights before in ' + source)
entities = []
for index, (position, reach, intensity, colour) in enumerate(lights):
    x, y, z = (round(value, 3) for value in position)
    entities.append(
        f'  - id: budget-light-{index}\n'
        f'    parent: highport\n'
        f'    transform:\n'
        f'      translation: [{x}, {y}, {z}]\n'
        f'    light:\n'
        f'      color: [{colour[0]}, {colour[1]}, {colour[2]}]\n'
        f'      intensity: {intensity:.1f}\n'
        f'      range: {reach:.1f}\n')
header = ('# Generated by scripts/make-light-budget-scene.py from orbit.yaml: '
          f'{len(lights)} more point lights over the station.\n')
target = os.path.join(os.path.dirname(source), 'light-budget.yaml')
with open(target, 'w') as file:
    file.write(header + text.replace(marker, ''.join(entities) + marker))
print(f'{target}: {len(lights)} lights added')
